#!/usr/bin/env node
// Copies an explicit allowlist of pure modules from src/lib/ into
// functions/shared/ so Cloud Functions (which only deploys the functions/
// directory — see firebase.json's functions[0].source) can import them.
//
// Every module here must be Firebase-free and import.meta.env-free, and must
// only import other modules on this same list (transitive closure). That
// invariant is enforced by src/lib/sharedSync.test.js, which also asserts
// byte-equality between src/lib/<name> and functions/shared/<name> — so this
// script must never transform file contents, only copy them verbatim.
//
// Usage: node ./scripts/sync-functions-shared.mjs  (also `npm run sync:shared`)

import { existsSync, mkdirSync, copyFileSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(__dirname, '..');

export const SHARED_MODULES = [
  'dates.js',
  'load.js',
  'priorityKeys.js',
  'priorityMetrics.js',
  'practiceFocus.js',
  'athleteIdentity.js',
  'athleteMemoryCore.js',
  'maturity.js',
  'tournaments.js',
  'injuries.js',
  'exerciseDb.js',
  'aiJson.js',
  'athleteContextCore.js',
  'planGenCore.js',
  'deferredPrioritiesCore.js',
  'digestCore.js',
  'growth.js',
  'guardianCore.js'
];

const SRC_DIR = path.join(repoRoot, 'src', 'lib');
const DEST_DIR = path.join(repoRoot, 'functions', 'shared');

const README_CONTENT = `# functions/shared

Generated by \`npm run sync:shared\` (\`scripts/sync-functions-shared.mjs\`) from
the pure modules in \`src/lib/\`. Do not edit the files in this directory —
edit the originals in \`src/lib\` and re-run the sync script instead. This
file is intentionally not on the sync allowlist so it survives re-syncs.

A vitest drift test (\`src/lib/sharedSync.test.js\`) asserts these copies stay
byte-identical to their \`src/lib\` sources, so CI fails on any unsynced edit.
`;

function main() {
  if (!existsSync(DEST_DIR)) {
    mkdirSync(DEST_DIR, { recursive: true });
  }

  const missing = [];
  const copied = [];

  for (const name of SHARED_MODULES) {
    const srcPath = path.join(SRC_DIR, name);
    const destPath = path.join(DEST_DIR, name);

    if (!existsSync(srcPath)) {
      missing.push(name);
      continue;
    }

    copyFileSync(srcPath, destPath);
    copied.push(name);
  }

  writeFileSync(path.join(DEST_DIR, 'README.md'), README_CONTENT);

  if (missing.length > 0) {
    console.error(`[sync:shared] missing source file(s): ${missing.join(', ')}`);
    process.exit(1);
  }

  console.log(`[sync:shared] copied ${copied.length} module(s) to functions/shared/:`);
  for (const name of copied) {
    console.log(`  - ${name}`);
  }
}

// Only run when executed directly (not when imported for SHARED_MODULES, e.g.
// by the drift test).
if (import.meta.url === `file://${process.argv[1]}`) {
  main();
}
