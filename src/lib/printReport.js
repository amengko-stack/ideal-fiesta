// Mounts the report, prints, then cleans up. Returns true if it printed.
export function printReport({ match, stats, analysis }) {
  if (typeof document === "undefined" || typeof window.print !== "function") return false;
  const style = document.createElement("style");
  style.setAttribute("data-print-report", "");
  style.textContent = PRINT_CSS;
  document.head.appendChild(style);

  const host = document.createElement("div");
  host.className = "print-root";
  host.innerHTML = buildReportHtml({ match, stats, analysis });
  document.body.appendChild(host);

  const cleanup = () => {
    if (host.parentNode) host.parentNode.removeChild(host);
    if (style.parentNode) style.parentNode.removeChild(style);
    window.removeEventListener("afterprint", cleanup);
  };
  window.addEventListener("afterprint", cleanup);
  try {
    window.print();
  } finally {
    // Safari never fires afterprint in some standalone modes — belt and braces.
    setTimeout(cleanup, 1000);
  }
  return true;
}
